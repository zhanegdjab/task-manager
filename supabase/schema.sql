-- 练习二 · 智能任务管理系统 · Supabase 数据库脚本
-- 用法：Supabase 控制台 → 左侧 SQL Editor → New query → 粘贴本文件全部内容 → 点 Run

-- ========== 1. 建表（与操作手册 4.2 节完全一致）==========
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  priority text not null default '中' check (priority in ('高', '中', '低')),
  completed boolean not null default false,
  created_at timestamptz not null default now()
);

-- ========== 2. 打开 RLS 并放行匿名读写（手册 4.3 节，不做这步写不进数据）==========
alter table public.tasks enable row level security;

drop policy if exists "Allow anon read" on public.tasks;
drop policy if exists "Allow anon insert" on public.tasks;
drop policy if exists "Allow anon update" on public.tasks;
drop policy if exists "Allow anon delete" on public.tasks;

create policy "Allow anon read" on public.tasks for select using (true);
create policy "Allow anon insert" on public.tasks for insert with check (true);
create policy "Allow anon update" on public.tasks for update using (true) with check (true);
create policy "Allow anon delete" on public.tasks for delete using (true);

-- ========== 3. 索引（列表按时间倒序、按优先级筛选都更快）==========
create index if not exists tasks_created_at_idx on public.tasks (created_at desc);
create index if not exists tasks_priority_idx on public.tasks (priority);
